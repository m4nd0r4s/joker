/// The tier of a pinned driver.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Tier {
    /// A Wasm driver, with the WIT world it exports.
    W,
    /// An external process, with the JDP version it speaks.
    X,
}

