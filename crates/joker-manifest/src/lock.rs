/// A value of the lock, already in canonical form.
#[derive(Debug, Clone, PartialEq)]
pub enum LockValue {
    /// A string.
    Text(String),
    /// An integer.
    Integer(i64),
    /// A float.
    Float(f64),
    /// A boolean.
    Bool(bool),
    /// A list.
    List(Vec<LockValue>),
    /// An inline table, in canonical key order.
    Table(Vec<(String, LockValue)>),
}

/// The fields of one entry, in canonical order.
pub type Fields = Vec<(String, LockValue)>;

/// A parsed lock.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct Lock {
    /// `version`.
    pub version: i64,
    /// `runtime`: the `jokerd` version where node facts were captured.
    pub runtime: Option<String>,
    /// `node`: the node where node facts were captured.
    pub node: Option<String>,
    /// Every section, by name, with its entries by key. `[accepted]` entries
    /// are keyed by subtable and key.
    pub sections: BTreeMap<String, BTreeMap<Vec<String>, Fields>>,
}

/// Where an artifact comes from (ref/02 §2.1.3).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Source {
    /// `oci://<registry>/<repo>:<tag>`, with the OCI manifest digest.
    Oci {
        /// The reference.
        reference: String,
        /// The `oci` digest.
        manifest: String,
    },
    /// `path:<path>`, relative to the lock folder with `/` separators.
    Path(String),
    /// `builtin:`, a profile compiled into the runtime.
    Builtin,
}

impl Source {
    /// A `path:` source for `target`, relative to `lock_dir`, written with `/`
    /// whatever the host, so the lock is the same on every machine.
    pub fn path(lock_dir: &Path, target: &Path) -> Self {
        let lock_dir = normalize(lock_dir);
        let target = normalize(target);
        let common = lock_dir
            .components()
            .zip(target.components())
            .take_while(|(a, b)| a == b)
            .count();
        let ups = lock_dir.components().count() - common;
        let mut parts: Vec<String> = std::iter::repeat_n("..".to_owned(), ups).collect();
        parts.extend(
            target
                .components()
                .skip(common)
                .map(|c| c.as_os_str().to_string_lossy().into_owned()),
        );
        Self::Path(parts.join("/"))
    }

    fn fields(&self) -> Fields {
        match self {
            Self::Oci {
                reference,
                manifest,
            } => vec![
                ("source".to_owned(), LockValue::Text(reference.clone())),
                ("oci".to_owned(), LockValue::Text(manifest.clone())),
            ],
            Self::Path(path) => {
                vec![("source".to_owned(), LockValue::Text(format!("path:{path}")))]
            }
            Self::Builtin => vec![("source".to_owned(), LockValue::Text("builtin:".to_owned()))],
        }
    }

    fn read(fields: &Fields) -> Option<Self> {
        let source = text(fields, "source")?;
        if let Some(path) = source.strip_prefix("path:") {
            return Some(Self::Path(path.to_owned()));
        }
        if source == "builtin:" {
            return Some(Self::Builtin);
        }
        Some(Self::Oci {
            reference: source.to_owned(),
            manifest: text(fields, "oci")?.to_owned(),
        })
    }
}

