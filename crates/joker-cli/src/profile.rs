//! `jk profile import` (ref/03 §2.2.19).

use std::io::Read as _;
use std::path::{Path, PathBuf};

use joker_manifest::csv_import::import_csv;
use joker_manifest::{Mode, Sources};

use crate::Failure;

fn default_out(name: &str) -> PathBuf {
    PathBuf::from("profiles").join(format!("{name}@1.profile.toml"))
}

/// `jk profile import csv <file> --name <n> --driver modbus [--out <f>] [--modicon]`.
pub fn import_csv_command(
    file: &str,
    name: &str,
    driver: &str,
    out: Option<&Path>,
    modicon: bool,
) -> Result<u8, Failure> {
    if driver != "modbus" {
        return Err(Failure::usage(format!(
            "--driver {driver}: only `modbus` is supported by the importer in 1.0"
        )));
    }
    let out = out
        .map(Path::to_path_buf)
        .unwrap_or_else(|| default_out(name));
    if out.exists() {
        return Err(Failure::usage(format!(
            "{} already exists: the importer never overwrites",
            out.display()
        )));
    }
    let text = if file == "-" {
        let mut buf = String::new();
        std::io::stdin()
            .read_to_string(&mut buf)
            .map_err(|e| Failure::usage(format!("reading stdin: {e}")))?;
        buf
    } else {
        std::fs::read_to_string(file).map_err(|e| Failure::usage(format!("{file}: {e}")))?
    };

    let mut sources = Sources::default();
    let source_name = if file == "-" {
        PathBuf::from("<stdin>")
    } else {
        PathBuf::from(file)
    };
    let id = sources.add(source_name, text.clone());
    let result = import_csv(id, &text, name, driver, modicon);
    let diags = result.diagnostics.sorted(&sources);
    for d in &diags {
        eprint!("{}", d.render(&sources, Mode::Prod));
    }
    let Some(toml) = result.toml else {
        return Ok(2);
    };
    if let Some(parent) = out.parent() {
        std::fs::create_dir_all(parent).map_err(|e| Failure::usage(format!("{e}")))?;
    }
    std::fs::write(&out, format!("# {}\n# Generated by jk profile import csv {file}. Resolve the \"# REVIEW\" lines and run jk profile test.\n{toml}", out.display()))
        .map_err(|e| Failure::usage(format!("writing {}: {e}", out.display())))?;
    println!("wrote {}", out.display());
    Ok(0)
}
