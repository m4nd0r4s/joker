#!/usr/bin/env python3
"""Fail on comments that AGENTS.md invariant 12 forbids.

Usage:

    python3 tools/comment-guard/comment_guard.py [PATH ...] [--root DIR]

Without a PATH the tracked files of the repository (``git ls-files``) are
checked. Two rules apply:

* Rust sources under ``crates/``, ``xtask/`` and ``tools/`` carry no comment
  other than doc comments (``///``, ``//!``, ``/** */`` and ``/*! */``).
  Python sources under ``tools/`` carry no ``#`` comment; the shebang on the
  first line is not a comment and docstrings are the documentation.
* Configuration files the project owns carry no comment at all: every
  ``*.toml``, the GitHub workflows (``.github/**/*.yml``) and the systemd
  units (``*.service``).

Text inside string literals, character literals and YAML block scalars is not
a comment. The files in ``ALLOWLIST`` are generated by tools that require
their own headers (ADR 0055) and are not checked. Each finding is printed as
``path:line: text`` and makes the exit status 1.
"""

import argparse
import fnmatch
import io
import os
import subprocess
import sys
import tokenize

ALLOWLIST = (
    "Cargo.lock",
    "*/Cargo.lock",
    "supply-chain/*.toml",
    "supply-chain/imports.lock",
    "*.proptest-regressions",
)

RUST_ROOTS = ("crates/", "xtask/", "tools/")


def allowlisted(path):
    """Return whether ``path`` is a generated file exempt from the check."""
    return any(fnmatch.fnmatch(path, pattern) for pattern in ALLOWLIST)


def classify(path):
    """Return the lexer for ``path``, or ``None`` when it is out of scope."""
    if allowlisted(path):
        return None
    name = os.path.basename(path)
    if path.endswith(".rs") and path.startswith(RUST_ROOTS):
        return rust_comments
    if path.endswith(".py") and path.startswith("tools/"):
        return python_comments
    if path.endswith(".toml"):
        return toml_comments
    if path.startswith(".github/") and name.endswith((".yml", ".yaml")):
        return yaml_comments
    if name.endswith(".service"):
        return unit_comments
    return None


def is_ident(ch):
    """Return whether ``ch`` can continue a Rust identifier."""
    return ch.isalnum() or ch == "_"


def rust_comments(text):
    """Yield ``(line, text)`` for every non-doc comment in Rust ``text``."""
    i = 0
    n = len(text)
    line = 1
    while i < n:
        ch = text[i]
        if ch == "\n":
            line += 1
            i += 1
        elif text.startswith("//", i):
            end = text.find("\n", i)
            end = n if end < 0 else end
            body = text[i:end]
            doc = (body.startswith("///") and not body.startswith("////")) or body.startswith("//!")
            if not doc:
                yield line, body
            i = end
        elif text.startswith("/*", i):
            start_line = line
            doc = (text.startswith("/**", i) and not text.startswith("/***", i) and not text.startswith("/**/", i)) or text.startswith("/*!", i)
            depth = 0
            j = i
            while j < n:
                if text.startswith("/*", j):
                    depth += 1
                    j += 2
                elif text.startswith("*/", j):
                    depth -= 1
                    j += 2
                    if depth == 0:
                        break
                else:
                    if text[j] == "\n":
                        line += 1
                    j += 1
            if not doc:
                yield start_line, text[i:j].split("\n", 1)[0]
            i = j
        elif ch in "rbc" and (i == 0 or not is_ident(text[i - 1])):
            j = i + 1
            if ch in "bc" and j < n and text[j] == "r":
                j += 1
            raw = text[j - 1] == "r"
            hashes = 0
            while raw and j < n and text[j] == "#":
                hashes += 1
                j += 1
            if j < n and text[j] == '"' and (raw or ch in "bc"):
                if raw:
                    close = '"' + "#" * hashes
                    end = text.find(close, j + 1)
                    end = n if end < 0 else end + len(close)
                else:
                    end = skip_quoted(text, j)
                line += text.count("\n", i, end)
                i = end
            elif ch == "b" and j < n and text[j] == "'":
                end = skip_char(text, j)
                i = end
            else:
                k = i
                while k < n and is_ident(text[k]):
                    k += 1
                i = k
        elif is_ident(ch):
            k = i
            while k < n and is_ident(text[k]):
                k += 1
            i = k
        elif ch == '"':
            end = skip_quoted(text, i)
            line += text.count("\n", i, end)
            i = end
        elif ch == "'":
            i = skip_char(text, i)
        else:
            i += 1


def skip_quoted(text, i):
    """Return the index just past the escaped string literal opened at ``i``."""
    j = i + 1
    n = len(text)
    while j < n:
        if text[j] == "\\":
            j += 2
        elif text[j] == '"':
            return j + 1
        else:
            j += 1
    return n


def skip_char(text, i):
    """Return the index past a character literal at ``i``, or past the lifetime tick."""
    n = len(text)
    if i + 1 < n and text[i + 1] == "\\":
        end = text.find("'", i + 2)
        return n if end < 0 else end + 1
    if i + 2 < n and text[i + 2] == "'":
        return i + 3
    return i + 1


def python_comments(text):
    """Yield ``(line, text)`` for every comment token in Python ``text``."""
    tokens = tokenize.generate_tokens(io.StringIO(text).readline)
    for token in tokens:
        if token.type != tokenize.COMMENT:
            continue
        row = token.start[0]
        if row == 1 and token.string.startswith("#!"):
            continue
        yield row, token.string


def toml_comments(text):
    """Yield ``(line, text)`` for every ``#`` comment in TOML ``text``."""
    i = 0
    n = len(text)
    line = 1
    while i < n:
        ch = text[i]
        if ch == "\n":
            line += 1
            i += 1
        elif text.startswith('"""', i) or text.startswith("'''", i):
            quote = text[i : i + 3]
            j = i + 3
            while j < n:
                if quote == '"""' and text[j] == "\\":
                    j += 2
                    continue
                if text.startswith(quote, j):
                    j += 3
                    while j < n and text[j] == quote[0]:
                        j += 1
                    break
                j += 1
            line += text.count("\n", i, j)
            i = j
        elif ch == '"':
            j = i + 1
            while j < n and text[j] not in '"\n':
                j += 2 if text[j] == "\\" else 1
            i = j + 1
        elif ch == "'":
            j = text.find("'", i + 1)
            i = n if j < 0 else j + 1
        elif ch == "#":
            end = text.find("\n", i)
            end = n if end < 0 else end
            yield line, text[i:end]
            i = end
        else:
            i += 1


def yaml_comments(text):
    """Yield ``(line, text)`` for every ``#`` comment in YAML ``text``."""
    block_indent = None
    for number, raw in enumerate(text.split("\n"), start=1):
        stripped = raw.lstrip(" ")
        indent = len(raw) - len(stripped)
        if block_indent is not None:
            if not stripped or indent > block_indent:
                continue
            block_indent = None
        position = yaml_comment_start(raw)
        content = raw if position is None else raw[:position]
        if position is not None:
            yield number, raw[position:].rstrip()
        tail = content.rstrip()
        if tail.endswith(("|", ">", "|-", ">-", "|+", ">+")):
            block_indent = indent
            if stripped.startswith("- "):
                block_indent = indent + 1


def yaml_comment_start(raw):
    """Return the index of the comment on a YAML line, outside quotes, or ``None``."""
    quote = None
    i = 0
    while i < len(raw):
        ch = raw[i]
        if quote:
            if quote == '"' and ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = None
        elif ch in "'\"" and (i == 0 or raw[i - 1] in " :[{,-"):
            quote = ch
        elif ch == "#" and (i == 0 or raw[i - 1] in " \t"):
            return i
        i += 1
    return None


def unit_comments(text):
    """Yield ``(line, text)`` for every comment line in a systemd unit."""
    for number, raw in enumerate(text.split("\n"), start=1):
        if raw.lstrip().startswith(("#", ";")):
            yield number, raw.strip()


def tracked_files(root):
    """Return the files tracked by git under ``root``."""
    output = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=root,
        check=True,
        capture_output=True,
    ).stdout
    return [name for name in output.decode("utf-8").split("\0") if name]


def check(root, paths):
    """Return the findings for ``paths`` relative to ``root``."""
    findings = []
    for path in sorted(paths):
        lexer = classify(path)
        if lexer is None:
            continue
        full = os.path.join(root, path)
        if not os.path.isfile(full):
            continue
        with open(full, encoding="utf-8") as handle:
            text = handle.read()
        for line, body in lexer(text):
            findings.append(f"{path}:{line}: {body.strip()}")
    return findings


def main(argv):
    """Run the guard and return the exit status."""
    parser = argparse.ArgumentParser(description="Fail on non-doc comments (AGENTS.md invariant 12).")
    parser.add_argument("paths", nargs="*", help="files to check, relative to the root; default: every tracked file")
    parser.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    args = parser.parse_args(argv)
    paths = args.paths or tracked_files(args.root)
    findings = check(args.root, paths)
    for finding in findings:
        print(finding)
    if findings:
        print(f"{len(findings)} comment(s) violate AGENTS.md invariant 12 (code has no comments; docstrings only)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
